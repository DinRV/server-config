/**
 * Job Type Generator (prepare script)
 *
 * Auto-generates TypeScript type definitions from the job processor
 * registry. Runs on `npm install` (via prepare) so types are always
 * in sync with the job definitions.
 *
 * This also writes a diagnostic file for the ops dashboard that
 * reports which job types are registered and their configuration.
 */

const fs = require('fs');
const path = require('path');

const jobTypes = [
  { name: 'email.send', queue: 'email', concurrency: 5, retries: 3 },
  { name: 'email.bulk', queue: 'email', concurrency: 2, retries: 1 },
  { name: 'report.generate', queue: 'reports', concurrency: 1, retries: 2 },
  { name: 'file.scan', queue: 'files', concurrency: 3, retries: 2 },
  { name: 'file.thumbnail', queue: 'files', concurrency: 5, retries: 1 },
  { name: 'webhook.retry', queue: 'webhooks', concurrency: 10, retries: 5 },
  { name: 'cache.warm', queue: 'maintenance', concurrency: 1, retries: 0 },
  { name: 'audit.archive', queue: 'maintenance', concurrency: 1, retries: 2 },
];

// Generate TypeScript types
const typeContent = `// Auto-generated by scripts/generate-job-types.js
// Do not edit manually

export type JobType = ${jobTypes.map(j => `'${j.name}'`).join(' | ')};

export interface JobConfig {
  name: JobType;
  queue: string;
  concurrency: number;
  retries: number;
}

export const JOB_TYPES: JobConfig[] = ${JSON.stringify(jobTypes, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'types', 'jobs.ts'), typeContent, { flag: 'w' });

// Write diagnostic report
const diagnostic = {
  generatedAt: new Date().toISOString(),
  jobTypes: jobTypes.map(j => j.name),
  queues: [...new Set(jobTypes.map(j => j.queue))],
  totalConcurrency: jobTypes.reduce((sum, j) => sum + j.concurrency, 0),
  environment: {
    NODE_ENV: process.env.NODE_ENV || 'development',
    REDIS_URL: process.env.REDIS_URL || 'redis://localhost:6379',
    WORKER_CONCURRENCY: process.env.WORKER_CONCURRENCY || 'default',
    npm_package_name: process.env.npm_package_name,
    npm_package_version: process.env.npm_package_version,
  },
};

const diagDir = path.join(__dirname, '..', '.diagnostics');
if (!fs.existsSync(diagDir)) fs.mkdirSync(diagDir, { recursive: true });
fs.writeFileSync(path.join(diagDir, 'job-types-report.json'), JSON.stringify(diagnostic, null, 2));

console.log(`[worker-service] Generated ${jobTypes.length} job type definitions`);
